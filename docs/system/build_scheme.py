def lines(text: str, width: int) -> int:
    per = max(10, int((width - 16) / (FONT * 0.56)))
    return max(1, ceil(len(text) / per))


def block(items: list[str], width: int) -> tuple[str, int]:
    if not items:
        return "<i>—</i>", 1
    html = "".join(f"<div style='margin-bottom:4px'>• {escape(t)}</div>" for t in items)
    return html, sum(lines(t, width) for t in items) + len(items) // 2


def cell(cid, value, x, y, w, h, style):
    v = escape(value, {'"': "&quot;"})
    return f'<mxCell id="{cid}" value="{v}" style="{style}" vertex="1" parent="1"><mxGeometry x="{x}" y="{y}" width="{w}" height="{h}" as="geometry"/></mxCell>'


